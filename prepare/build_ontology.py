"""Check curry.ttl and derive the files the site uses from it.

    python3 prepare/build_ontology.py

curry.ttl is the source. This writes curry.owl (RDF/XML, for Protégé) and
ontology.js (both texts as JS strings, so Comunica can query the ontology in
the browser without fetching anything — that also works in the Canvas build).
"""
import json
from pathlib import Path
import rdflib
import rdflib.compare

ROOT = Path(__file__).resolve().parent.parent
ttl = (ROOT / "curry.ttl").read_text()
g = rdflib.Graph().parse(data=ttl, format="turtle")
owl = g.serialize(format="xml")
back = rdflib.Graph().parse(data=owl, format="xml")
assert rdflib.compare.isomorphic(g, back), "RDF/XML lost triples"
(ROOT / "curry.owl").write_text(owl)
(ROOT / "ontology.js").write_text(
    "// Generated by prepare/build_ontology.py from curry.ttl — edit that file instead.\n"
    f"const CURRY_TTL = {json.dumps(ttl, ensure_ascii=False)};\n"
    f"const CURRY_OWL = {json.dumps(owl, ensure_ascii=False)};\n")
print(f"{len(g)} triples; wrote curry.owl and ontology.js")
